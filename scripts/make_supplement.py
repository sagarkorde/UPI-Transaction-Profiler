"""Write results/SUPPLEMENT.md: every statistic, at every budget, with CIs."""
import json
import os

import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
A = os.environ.get("ANALYSIS_DIR", os.path.join(ROOT, "results", "analysis"))
r = lambda f: pd.read_csv(os.path.join(A, f))
main, em, gr, fs, fp, ab, sg, pr = (r("main_base.csv"), r("emerging_pooled.csv"), r("emerging_groups.csv"),
                                    r("frontier_summary.csv"), r("frontier_points.csv"), r("ablation.csv"),
                                    r("signals.csv"), r("premium.csv"))
summ = json.load(open(os.path.join(A, "summary.json")))
f3 = lambda x: "—" if pd.isna(x) else f"{x:.3f}"
out = ["# Supplementary results", "",
       f"Protocol SHA-256: `{summ['config_sha256']}` · runs: {summ['n_runs']} · generated by `scripts/make_supplement.py` "
       "from `results/analysis/`.", "",
       "All recall values are seed-averaged (5 seeds). CIs: 95% percentile bootstrap over review windows (2,000 resamples). "
       "p: two-sided paired sign-flip permutation test vs SUP (10,000 draws); p_holm: Holm-adjusted within dataset × budget.", ""]

man = json.load(open(os.path.join(ROOT, "data", "manifest.json")))
import hashlib
hsh = lambda f: hashlib.sha256(open(os.path.join(ROOT, "configs", f), "rb").read()).hexdigest()
out += ["## S0. Full hashes", "", "| item | SHA-256 |", "|---|---|"]
for k, m in man.items():
    out.append(f"| data: {m['file']} ({k}) | `{m['sha256']}` |")
out += [f"| configs/protocol.yaml (v1.0) | `{hsh('protocol.yaml')}` |",
        f"| configs/amendment_v1_1.yaml | `{hsh('amendment_v1_1.yaml')}` |", ""]
a2 = r("assumption_a2.csv")
out += ["## S0b. Assumption A2: SUP precision by rank band (stationary test period)", "",
        "| dataset | band of c | reviews | frauds | precision [95% CI] |", "|---|---|---|---|---|"]
for _, x in a2.iterrows():
    out.append(f"| {x.dataset} | {x.band} | {x.reviews:.0f} | {x.frauds:.1f} | {f3(x.precision)} [{f3(x.lo)}, {f3(x.hi)}] |")
out.append("")
out += ["## S1. Stationary test period: recall@budget for every policy and budget", ""]
for ds in main.dataset.unique():
    out += [f"### {ds}", "", "| c | policy | recall [95% CI] | Δ vs SUP [95% CI] | p_holm | seed SD | amount recall |",
            "|---|---|---|---|---|---|---|"]
    for _, x in main[main.dataset == ds].iterrows():
        out.append(f"| {x.c} | {x.policy} | {f3(x.recall)} [{f3(x.lo)}, {f3(x.hi)}] | {x['diff']:+.3f} "
                   f"[{x.diff_lo:+.3f}, {x.diff_hi:+.3f}] | {f3(x.p_holm)} | {f3(x.sd_seed)} | {f3(x.amount_recall)} |")
    out.append("")

out += ["## S2. Held-out-mechanism scenarios (pooled over groups)", ""]
for ds in em.dataset.unique():
    out += [f"### {ds}", "", "| c | policy | overall [95% CI] | novel [95% CI] | Δnovel vs SUP [95% CI] | p_holm (novel) |",
            "|---|---|---|---|---|---|"]
    for _, x in em[em.dataset == ds].iterrows():
        out.append(f"| {x.c} | {x.policy} | {f3(x.overall)} [{f3(x.overall_lo)}, {f3(x.overall_hi)}] | {f3(x.novel)} "
                   f"[{f3(x.novel_lo)}, {f3(x.novel_hi)}] | {x.novel_diff:+.3f} [{x.novel_diff_lo:+.3f}, {x.novel_diff_hi:+.3f}] "
                   f"| {f3(x.get('novel_p_holm'))} |")
    out.append("")

out += ["## S3. Per held-out group (c = 1)", "", "| dataset | group | policy | overall | novel | novel frauds | seed SD (novel) |",
        "|---|---|---|---|---|---|---|"]
for _, x in gr.iterrows():
    out.append(f"| {x.dataset} | {x.group} | {x.policy} | {f3(x.overall)} | {f3(x.novel)} | {int(x.novel_frauds)} | {f3(x.sd_novel)} |")
out.append("")

out += ["## S4. Protection–cost frontier (c = 1)", "", "| dataset | family | parameter | overall (held-out) | novel | overall (stationary) |",
        "|---|---|---|---|---|---|"]
for _, x in fp.iterrows():
    out.append(f"| {x.dataset} | {x.family} | {x.param} | {f3(x.overall)} | {f3(x.novel)} | {f3(x.base_overall)} |")
out += ["", "Pre-registered frontier summary (best novel recall within relative overall-recall cost τ):", "",
        "| dataset | τ | DRT | FUSE | Δ [95% CI] | bootstrap P(Δ ≤ 0) |", "|---|---|---|---|---|---|"]
for _, x in fs.iterrows():
    out.append(f"| {x.dataset} | {x.tau} | {f3(x.drt)} | {f3(x.fuse)} | {x['diff']:+.3f} [{x.diff_lo:+.3f}, {x.diff_hi:+.3f}] | {x.p_boot_le0:.3f} |")
out.append("")

out += ["## S5. Ablations (c = 1, ρ = 0.1)", "", "| dataset | variant | stationary recall | cost [95% CI] | novel [95% CI] |",
        "|---|---|---|---|---|"]
for _, x in ab.iterrows():
    out.append(f"| {x.dataset} | {x.policy} | {f3(x.base_recall)} | {x.base_cost:+.3f} [{x.base_cost_lo:+.3f}, {x.base_cost_hi:+.3f}] "
               f"| {f3(x.get('novel'))} [{f3(x.get('novel_lo'))}, {f3(x.get('novel_hi'))}] |")
out.append("")

out += ["## S6. Threshold-free signal quality on the test period (mean ± SD over runs)", "",
        "| dataset | setting | signal | AP | ROC-AUC | AP (novel vs legit) | ROC-AUC (novel vs legit) |", "|---|---|---|---|---|---|---|"]
for _, x in sg.iterrows():
    out.append(f"| {x.dataset} | {x.kind} | {x.signal} | {f3(x.ap)} ± {f3(x.ap_sd)} | {f3(x.auc)} ± {f3(x.auc_sd)} | "
               f"{f3(x.ap_novel)} ± {f3(x.ap_novel_sd)} | {f3(x.auc_novel)} ± {f3(x.auc_novel_sd)} |")
out.append("")

out += ["## S7. Calibration-period estimate vs realised stationary cost of ρ (c = 1)", "",
        "| dataset | ρ | estimated (calibration) | realised (test) |", "|---|---|---|---|"]
for _, x in pr.iterrows():
    out.append(f"| {x.dataset} | {x.rho} | {x.premium_calib:.4f} | {x.premium_test:.4f} |")
out += ["", f"Correlation over all (dataset, ρ): {summ['premium_corr']:.3f}", "",
        "## S8. Adaptive allocation", "", f"Mean ρ of DRT-ADAPT over the test period (c = 1): `{json.dumps(summ['mean_rho_adaptive'])}`", "",
        f"Tuned fusion weight ω* = 1 in {summ['fuse_w_star_is_1']} of {summ['n_runs']} runs.", "",
        f"DRT relative stationary cost by dataset and budget: `{summ['drt_rel_cost_by']}`"]
gq = r("group_signal.csv")
out += ["", "## S9. Exploratory (not in the frozen protocol): per-group signal quality vs DRT gain (c = 1)", "",
        "Figure: `figures/fig_groups.png`.", "",
        "| dataset | group | AP novel (SUP) | AP novel (anomaly) | novel recall SUP | novel recall DRT | DRT gain |",
        "|---|---|---|---|---|---|---|"]
for _, x in gq.iterrows():
    out.append(f"| {x.dataset} | {x.group} | {f3(x.ap_novel_SUP)} | {f3(x.ap_novel_ANO)} | {f3(x.SUP)} | {f3(x.DRT)} | {x.drt_gain:+.3f} |")
out += ["", f"Spearman r_s = {summ['group_spearman']:.3f} (p = {summ['group_spearman_p']:.3f}, n = {summ['n_groups']})"]
mf = json.load(open(os.path.join(ROOT, "results", "runs", "_manifest.json")))
out += ["", "## S10. Held-out scenario candidates and exclusions", "",
        "Rule (fixed in configs/protocol.yaml before any test evaluation): keep a candidate group only if it has at least "
        "10 frauds in the test period (statistical power). Candidate sets: BankSim = four categories with most fraud overall; "
        "TabFormer = all card channels; ULB = all four k-means clusters (fitted on pre-test frauds, amendment v1.1).", "",
        "| dataset | candidate group | test frauds | retained |", "|---|---|---|---|"]
for ds, sc in mf["scenarios"].items():
    for g, n in sc["test_fraud_counts"].items():
        out.append(f"| {ds} | {g} | {n} | {'yes' if g in sc['holdout_groups'] else 'no (< 10 test frauds)'} |")
open(os.path.join(ROOT, "results", "SUPPLEMENT.md"), "w").write("\n".join(out) + "\n")
print("wrote results/SUPPLEMENT.md")
